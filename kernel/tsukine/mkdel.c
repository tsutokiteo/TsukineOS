#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <unistd.h>
#include <fcntl.h>
#include "del.h"
#include "tsukine_abi.h"

#ifndef DEL_F_COMPAT
#  define DEL_F_COMPAT  TSUKI_F_COMPAT
#endif

static const struct {
    const char *name;
    uint32_t    subcmd;
} native_tab[] = {
    { "tsukine_gui_create_window",  TSUKI_GUI_CREATE_WIN  },
    { "tsukine_gui_destroy_window", TSUKI_GUI_DESTROY_WIN },
    { "tsukine_gui_show_window",    TSUKI_GUI_SHOW_WIN    },
    { "tsukine_fs_create",          TSUKI_FS_CREATE       },
    { "tsukine_fs_close",           TSUKI_FS_CLOSE        },
    { "tsukine_fs_read",            TSUKI_FS_READ         },
    { "tsukine_fs_write",           TSUKI_FS_WRITE        },
    { "tsukine_fs_delete",          TSUKI_FS_DELETE       },
    { "tsukine_proc_terminate",     TSUKI_PROC_TERM       },
    { "tsukine_proc_create",        TSUKI_PROC_CREATE     },
    { "tsukine_mem_alloc",          TSUKI_MEM_ALLOC       },
    { "tsukine_mem_free",           TSUKI_MEM_FREE        },
};

static const struct {
    const char *name;
    uint32_t    win_ssn;
    uint32_t    tsuki_sys;
    uint32_t    subcmd;
} compat_map[] = {
    { "NtClose",              WIN_NtClose,              TSUKI_NR_FS,   TSUKI_FS_CLOSE   },
    { "NtCreateFile",         WIN_NtCreateFile,         TSUKI_NR_FS,   TSUKI_FS_CREATE  },
    { "NtReadFile",           WIN_NtReadFile,           TSUKI_NR_FS,   TSUKI_FS_READ    },
    { "NtWriteFile",          WIN_NtWriteFile,          TSUKI_NR_FS,   TSUKI_FS_WRITE   },
    { "NtDeleteFile",         WIN_NtDeleteFile,         TSUKI_NR_FS,   TSUKI_FS_DELETE  },
    { "NtTerminateProcess",   WIN_NtTerminateProcess,   TSUKI_NR_PROC, TSUKI_PROC_TERM  },
    { "NtAllocateVirtualMemory", WIN_NtAllocateVM,      TSUKI_NR_MEM,  TSUKI_MEM_ALLOC  },
    { "NtFreeVirtualMemory",  WIN_NtFreeVM,             TSUKI_NR_MEM,  TSUKI_MEM_FREE   },
};

static uint8_t *buf  = NULL;
static size_t   cap  = 0;
static size_t   used = 0;

static void grow(size_t need)
{
    if (used + need <= cap) return;
    size_t n = (used + need + 4095) & ~(size_t)4095;
    uint8_t *p = realloc(buf, n);
    if (!p) { perror("realloc"); abort(); }
    buf = p; cap = n;
}

static size_t emit(const void *data, size_t len)
{
    grow(len);
    memcpy(buf + used, data, len);
    used += len;
    return used - len;
}

static size_t emit_u32(uint32_t v) { return emit(&v, sizeof(v)); }

int main(int argc, char **argv)
{
    const char *out = (argc > 1) ? argv[1] : "syscall.del";
    uint32_t abi_ver = (argc > 2) ? (uint32_t)atoi(argv[2]) : 1u;

    grow(sizeof(del_header_t));
    used = sizeof(del_header_t);

    size_t entry_area_start = used;

    size_t total_entries = 2 + sizeof(native_tab)/sizeof(native_tab[0])
                          + sizeof(compat_map)/sizeof(compat_map[0]);
    size_t str_off = sizeof(del_header_t)
                   + total_entries * sizeof(del_entry_t)
                   + sizeof(compat_map)/sizeof(compat_map[0]) * 8
                   + 4;

    grow(str_off);
    used = str_off;

    size_t str_size = 0;

    /* NOTE payload */
    const char *note_msg = "TsukineOS ABI + Windows compat map, auto-generated by mkdel";
    size_t note_len = strlen(note_msg) + 1;
    grow(note_len);
    memcpy(buf + str_off + str_size, note_msg, note_len);
    str_size += note_len;

    /* 退回 entry 区 */
    used = entry_area_start;

    /* 原生条目 */
    for (size_t i = 0; i < sizeof(native_tab)/sizeof(native_tab[0]); i++) {
        size_t name_len = strlen(native_tab[i].name) + 1;
        grow(name_len);
        memcpy(buf + str_off + str_size, native_tab[i].name, name_len);
        uint32_t name_off = (uint32_t)str_size;
        str_size += name_len;

        del_entry_t e;
        memset(&e, 0, sizeof(e));
        e.abi_nr   = native_tab[i].subcmd;
        e.op       = DEL_OP_ADD;
        e.flags    = 0;
        e.name_off = name_off;
        e.size     = 0;
        emit(&e, sizeof(e));
    }

    /* 兼容条目 */
    for (size_t i = 0; i < sizeof(compat_map)/sizeof(compat_map[0]); i++) {
        size_t name_len = strlen(compat_map[i].name) + 1;
        grow(name_len);
        memcpy(buf + str_off + str_size, compat_map[i].name, name_len);
        uint32_t name_off = (uint32_t)str_size;
        str_size += name_len;

        del_entry_t e;
        memset(&e, 0, sizeof(e));
        e.abi_nr   = compat_map[i].win_ssn;
        e.op       = DEL_OP_ADD;
        e.flags    = DEL_F_COMPAT;
        e.name_off = name_off;
        e.size     = 8;
        emit(&e, sizeof(e));
        emit_u32(compat_map[i].tsuki_sys);
        emit_u32(compat_map[i].subcmd);
    }

    /* NOTE entry */
    {
        del_entry_t e;
        memset(&e, 0, sizeof(e));
        e.abi_nr   = 0;
        e.op       = DEL_OP_NOTE;
        e.flags    = 0;
        e.name_off = 0;
        e.size     = (uint32_t)note_len;
        emit(&e, sizeof(e));
        grow(e.size);
        memcpy(buf + used, note_msg, e.size);
        used += e.size;
    }

    /* REQUIRE entry */
    {
        del_entry_t e;
        memset(&e, 0, sizeof(e));
        e.abi_nr   = 0;
        e.op       = DEL_OP_REQUIRE;
        e.flags    = 0;
        e.name_off = 0;
        e.size     = 4;
        emit(&e, sizeof(e));
        emit_u32(abi_ver);
    }

    /* ★ 关键修复：把 used 拉到 string pool 末尾，确保名字数据写进文件 */
    used = str_off + str_size;

    /* header */
    del_header_t hdr;
    memset(&hdr, 0, sizeof(hdr));
    hdr.magic       = DEL_MAGIC;
    hdr.format_ver  = DEL_FORMAT_VER;
    hdr.abi_ver     = abi_ver;
    hdr.entry_count = (uint32_t)total_entries;
    hdr.entry_off   = (uint32_t)sizeof(del_header_t);
    hdr.string_off  = (uint32_t)str_off;
    hdr.string_size = (uint32_t)str_size;
    memcpy(buf, &hdr, sizeof(hdr));

    int fd = open(out, O_WRONLY | O_CREAT | O_TRUNC, 0644);
    if (fd < 0) { perror("open"); return 1; }
    if (write(fd, buf, used) != (ssize_t)used) { perror("write"); close(fd); return 1; }
    close(fd);

    printf("mkdel: wrote %s (%zu bytes)\n", out, used);
    printf("  entries: %zu native + %zu compat + 2 meta = %zu\n",
           sizeof(native_tab)/sizeof(native_tab[0]),
           sizeof(compat_map)/sizeof(compat_map[0]), total_entries);
    printf("  strings: %zu bytes @ off %zu\n", str_size, str_off);
    free(buf);
    return 0;
}